const { app, BrowserWindow, contextBridge, ipcMain } = require('electron');
const path = require('path');
const { initCredentialsService, preloadCredentials } = require('./helpers/credentials');

// Rule 2: Enable sandbox globally
app.enableSandbox();

function createWindow() {
  const mainWindow = new BrowserWindow({
    width: 800,
    height: 600,
    webPreferences: {
      nodeIntegration: false,
      contextIsolation: true,
      sandbox: true,
      webSecurity: true,
      preload: path.join(__dirname, 'preload.js')
    }
  });

  mainWindow.loadFile('index.html');
}

app.whenReady().then(() => {
  // Rule 5: Initialize dependencies
  initCredentialsService();
  
  createWindow();

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) {
      createWindow();
    }
  });
});

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') {
    app.quit();
  }
});